import { randomUUID } from 'node:crypto';
import { messageOf, stackOf } from '../../src/platform/error/message-of';

/** The gate commands: the name is in the prefix of every stderr line. */
export type GateName = 'm3' | 'm4' | 'm5' | 'm6' | 'm7' | 'm8' | 'm9';

/** How the gate ended: whether the claim is proven and whether it cleaned up after itself. */
export interface GateResult {
  readonly ok: boolean;
  readonly clean: boolean;
}

/**
 * Maps a result to an exit code: 0 means proven and cleaned up; 1 means not proven; 3 means proven,
 * but residue remains.
 */
export function exitCodeOf({ ok, clean }: GateResult): number {
  if (!ok) return 1;

  return clean ? 0 : 3;
}

/** The gate environment's database: the same Postgres installation, another database (ADR 0041). */
export const GATE_DATABASE = 'app_db_gate';

/** The binding of the gate workspace: generated by the prepare step (`gate prepare`). */
export const GATE_MAPPING_FILE = '/etc/app/gate/notion-mapping.yaml';

/**
 * The gate lives in a separate environment (ADR 0041): its own database, its own Notion workspace
 * and binding, its own GBrain client. The `gate` service in Compose sets the values, without the
 * token of the main workspace. Here the gate refuses to start if even one value is not its own,
 * because anything else would let the gate write to the main environment.
 */
export function assertGateEnvironment(env: NodeJS.ProcessEnv): void {
  const problems: string[] = [];
  const database = databaseOf(env.DATABASE_URL);

  if (database !== GATE_DATABASE) {
    problems.push(`DATABASE_URL names ${database ?? 'no database'}, not ${GATE_DATABASE}`);
  }

  if (!env.NOTION_API_TOKEN) problems.push('NOTION_API_TOKEN is empty');
  if (env.NOTION_MAPPING_FILE !== GATE_MAPPING_FILE) {
    problems.push(
      `NOTION_MAPPING_FILE is ${env.NOTION_MAPPING_FILE ?? 'unset'}, not ${GATE_MAPPING_FILE}`,
    );
  }

  if (!env.GBRAIN_CLIENT_ID || !env.GBRAIN_CLIENT_SECRET) {
    problems.push('the gate GBrain client is unset');
  }

  if (problems.length > 0) {
    throw new Error(
      `this is not the gate environment — ${problems.join('; ')}; run the gate through infra/bin/gate`,
    );
  }
}

function databaseOf(url: string | undefined): string | null {
  if (!url) return null;

  try {
    return new URL(url).pathname.replace(/^\//, '') || null;
  } catch {
    return null;
  }
}

/**
 * Sets the environment of the second App instance before the application is built: the
 * environment check and the configuration read it when the module is imported, so enabling the
 * runner later would be too late. The review schedule is set here as well, because the gate
 * conducts the review itself, not the producer.
 *
 * The gate's channel is its own and confined to loopback: the secret and the bot token are
 * one-time, the chat is a dummy, and the Bot API is the gate's listener (`bot-api.ts`) on the
 * same loopback. The gate sends nothing to the real Telegram and does not pass the real token on
 * anywhere. What the App would send to the person is visible in the listener, and the person's
 * messages for the channel scenarios arrive at the gate's own webhook.
 */
function prepareEnvironment(): void {
  process.env.WORKERS_ENABLED = 'false';
  process.env.RUNNER_ENABLED = 'true';
  process.env.PORT = process.env.GATE_PORT ?? '3100';

  process.env.TELEGRAM_WEBHOOK_SECRET = randomUUID();
  process.env.TELEGRAM_BOT_TOKEN = `gate-${randomUUID()}`;
  process.env.TELEGRAM_ALLOWED_CHAT_ID = '1';
  process.env.TELEGRAM_API_BASE = `http://127.0.0.1:${process.env.GATE_BOT_API_PORT ?? '3101'}`;

  // The gate's review schedule: the current occurrence of each is open for its whole period, so a
  // review can be held at any time of day, whatever schedule the service inherited from the main
  // environment.
  process.env.REVIEW_DAILY_CONTROL = 'daily 00:00';
  process.env.REVIEW_WEEKLY_CONTROL = 'weekly mon 00:00';
  process.env.REVIEW_STRATEGIC = 'monthly 1 00:00';
  process.env.REVIEW_DEEP = 'quarterly 1 00:00';
}

/**
 * Launches a gate command: checks that the environment is the gate environment, sets the
 * environment of the second App instance, conducts `run` and sets the exit code. It is the only
 * gate entry point that touches the environment (`INV-093`), and it has only light imports,
 * because everything that pulls in `AppModule` reads the environment when imported, before it is
 * set.
 *
 * `run` is called synchronously before the first delay, so an argument parsing error is a message
 * without a stack, and a run failure comes with a stack. A code already set by a stop signal
 * (`128 + signal`) is not overridden by the verdict: a scenario that fails after the application
 * is closed does not cancel the stop.
 */
export function launchGate(name: GateName, run: () => Promise<GateResult>): void {
  const fail = (text: string): void => {
    process.stderr.write(`${name} gate: ${text}\n`);
    process.exitCode ??= 1;
  };
  let finished: Promise<GateResult>;

  try {
    assertGateEnvironment(process.env);
    prepareEnvironment();
    finished = run();
  } catch (error) {
    fail(messageOf(error));

    return;
  }

  void finished
    .then((result) => {
      process.exitCode ??= exitCodeOf(result);
    })
    .catch((error: unknown) => fail(stackOf(error) ?? messageOf(error)));
}
