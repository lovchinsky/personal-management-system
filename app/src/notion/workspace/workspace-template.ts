import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { Document, isMap, isPair, isScalar, parse } from 'yaml';
import { z } from 'zod';
import { COMMAND } from './workspace-installation';

/**
 * The generator of an empty binding, for a workspace of another shape where the databases already
 * exist and the binding is written by hand.
 *
 * The slots come from `contracts/canonical.yaml`, the contract, not from its implementation in
 * the App. That is why a divergence between them becomes visible on its own. A canonical field
 * missing from the binding schema appears in the template, and the App names it an extra key. The
 * template does not include a field that has disappeared, and the App requires it and reports it
 * as missing.
 *
 * The generator proposes no values: the binding is the decision of the workspace owner, and a
 * wrongly guessed binding goes unnoticed, whereas an empty slot is seen at once.
 */

const HEADER = ` Binding of the canonical model to a physical Notion workspace.

 Filled in by hand — on your own or with Claude. Not tracked by git, like the
 environment file: it describes one workspace, not the system. It is not a
 secret — it holds identifiers only, so it is safe to print in logs and quote
 in errors.

 The App reads this file once, at startup, and refuses to start while a single
 null is left.

 Every canonical field gets one of the representation kinds declared in
 contracts/canonical.yaml -> representation_kinds:

   { kind: native,    propertyId: aGCp }
   { kind: relation,  propertyId: o%7B%40c, dataSourceId: 4ab7da3f-...,
                      twoWay: true, syncedPropertyId: C%5CFR }
   { kind: traversed, via: aFBO, rule: through_key_results }
   { kind: page_body }                 prose in the page body, read whole
   { kind: gbrain }                    accumulated in the GBrain anchor
   { kind: absent,    reason: no such property }

 null means "not filled in yet" and is nothing like absent: the App treats the
 first as unfinished work and the second as a declared decision.

 Generated by \`${COMMAND} template\` from contracts/canonical.yaml.`;

const COMMENTS: Readonly<Record<string, string>> = {
  workspace: ' Identifies the workspace this file belongs to. The App does not use it.',
  data_sources: ' Canonical type -> id of the physical data source.',
  fields: ' Canonical type -> canonical field -> representation.',
  signals:
    ' Computed properties of the workspace, read as detector evidence and never\n' +
    ' written. Canonical fields they are not: each repeats a fact the model\n' +
    ' already expresses, only cheaper. A sample is at the end of this file.',
  options:
    ' Option ids are needed only by fields bound as native: under page_body a\n' +
    ' value is recognised by the section text, so no option id exists. An empty\n' +
    ' {} is an answer too — no such field is bound as native. A sample of the\n' +
    ' blocks is at the end of this file.',
};

interface EnumSlot {
  readonly id: string;
  readonly title: string;
  readonly values: readonly string[];
}

/** The part of the contract the template is built from. */
const contractSchema = z.object({
  field_contract: z.record(z.string(), z.record(z.string(), z.unknown())),
  signals: z.record(z.string(), z.unknown()).optional(),
  known_non_canonical: z
    .array(z.object({ canonical_type: z.string().trim().min(1), value: z.string().trim().min(1) }))
    .optional(),
});

type Contract = z.infer<typeof contractSchema>;

function readContract(file: string): Contract {
  const parsed = contractSchema.safeParse(parse(readFileSync(file, 'utf8')));
  if (!parsed.success) {
    throw new Error(`${file}: ${z.prettifyError(parsed.error)}`);
  }

  return parsed.data;
}

interface TemplateOptions {
  /** `contracts/canonical.yaml`: the template's slots. */
  readonly canonical: string;
  /** Where the template goes: the installation's binding file. */
  readonly binding: string;
  readonly log: (line: string) => void;
}

/** Writes an empty binding; the generator never overwrites a filled binding. */
export function writeBindingTemplate({ canonical, binding, log }: TemplateOptions): void {
  if (existsSync(binding)) {
    throw new Error(`${binding} already exists. The generator never overwrites a filled binding.`);
  }

  const contract = readContract(canonical);
  const fieldContract = contract.field_contract;
  const enums = enumSlots(fieldContract);

  mkdirSync(dirname(binding), { recursive: true });

  writeFileSync(
    binding,
    render(
      fieldContract,
      enums,
      knownNonCanonical(contract.known_non_canonical ?? [], enums),
      Object.keys(contract.signals ?? {}),
    ),
    { encoding: 'utf8', mode: 0o644 },
  );

  log(`Skeleton written: ${binding}`);
}

/** The contract writes a field with mutually exclusive values as `A | B | C`. */
function enumSlots(fieldContract: Contract['field_contract']): readonly EnumSlot[] {
  const slots: EnumSlot[] = [];

  for (const [type, block] of Object.entries(fieldContract)) {
    for (const [field, marker] of Object.entries(block)) {
      if (typeof marker !== 'string' || !marker.includes('|')) continue;

      slots.push({
        id: `${type}.${field}`,
        title: titleCase(`${type} ${field}`),
        values: marker.split('|').map((value) => value.trim()),
      });
    }
  }

  return slots;
}

/**
 * The contract refers to a value outside the canonical model (`D5`) through a field, “Task
 * Status”, so the set is found by matching the title back.
 */
function knownNonCanonical(
  entries: NonNullable<Contract['known_non_canonical']>,
  enums: readonly EnumSlot[],
): ReadonlyMap<string, readonly string[]> {
  const declared = new Map<string, string[]>();

  for (const { canonical_type: canonicalType, value } of entries) {
    const slot = enums.find(({ title }) => title.toLowerCase() === canonicalType.toLowerCase());
    if (!slot) {
      throw new Error(
        `known_non_canonical "${canonicalType}" matches no value set declared by the contract`,
      );
    }

    declared.set(slot.id, [...(declared.get(slot.id) ?? []), value]);
  }

  return declared;
}

function render(
  fieldContract: Contract['field_contract'],
  enums: readonly EnumSlot[],
  declared: ReadonlyMap<string, readonly string[]>,
  signals: readonly string[],
): string {
  const types = Object.keys(fieldContract);

  const document = new Document({
    workspace: null,
    data_sources: Object.fromEntries(types.map((type) => [type, null])),
    fields: Object.fromEntries(
      types.map((type) => [
        type,
        Object.fromEntries(Object.keys(fieldContract[type]).map((field) => [field, null])),
      ]),
    ),
    options: {},
  });

  document.commentBefore = HEADER;

  for (const [key, comment] of Object.entries(COMMENTS)) commentBeforeKey(document, key, comment);

  spaceBetweenTypes(document);

  // Signals are entirely optional, so in the template they are a sample, not slots set to null:
  // an unbound signal must be absent from the file, not empty.
  document.comment = [
    ' Sample option id sets:',
    '',
    ...indent(sample(enums, declared)),
    '',
    ' Computed properties this workspace happens to have. Optional in full —',
    ' an absent signal is not a degradation, the model reaches the same fact',
    ' the longer way. Uncomment the ones that exist:',
    '',
    ...indent(new Document({ signals: Object.fromEntries(signals.map((id) => [id, null])) })),
  ].join('\n');

  return String(document);
}

/** YAML adds `#` to every comment line; the space after it is ours. */
function indent(document: Document): string[] {
  return String(document)
    .trimEnd()
    .split('\n')
    .map((line) => ` ${line}`);
}

/** The sample is built by the same serializer; YAML itself does the commenting. */
function sample(
  enums: readonly EnumSlot[],
  declared: ReadonlyMap<string, readonly string[]>,
): Document {
  return new Document({
    options: Object.fromEntries(
      enums.map(({ id, values }) => {
        const canonical = Object.fromEntries(values.map((value) => [value, null]));
        const nonCanonical = declared.get(id);

        return [
          id,
          nonCanonical
            ? {
                canonical,
                known_non_canonical: Object.fromEntries(nonCanonical.map((value) => [value, null])),
              }
            : { canonical },
        ];
      }),
    ),
  });
}

function commentBeforeKey(document: Document, key: string, comment: string): void {
  const contents = document.contents;

  if (!isMap(contents)) {
    throw new Error('the document is not a block of keys');
  }

  for (const item of contents.items) {
    if (!isPair(item) || !isScalar(item.key) || item.key.value !== key) continue;

    item.key.commentBefore = comment;
    item.key.spaceBefore = key !== 'workspace';
  }
}

function spaceBetweenTypes(document: Document): void {
  const fields = document.get('fields', true);

  if (!isMap(fields)) return;

  for (const [index, item] of fields.items.entries()) {
    if (index > 0 && isPair(item) && isScalar(item.key)) item.key.spaceBefore = true;
  }
}

function titleCase(value: string): string {
  return value
    .split(/[\s_]+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}
