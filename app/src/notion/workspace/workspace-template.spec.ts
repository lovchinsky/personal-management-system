import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { parse } from 'yaml';
import { z } from 'zod';
import { loadBinding } from '../binding/load-binding';
import { writeBindingTemplate } from './workspace-template';

const CANONICAL = resolve(__dirname, '../../../../contracts/canonical.yaml');

/** The canonical types and fields, as the contract declares them. */
const FIELD_CONTRACT = z
  .object({ field_contract: z.record(z.string(), z.record(z.string(), z.unknown())) })
  .parse(parse(readFileSync(CANONICAL, 'utf8'))).field_contract;

describe('notion template', () => {
  let folder: string;
  let binding: string;
  let lines: string[];
  const log = (line: string): void => {
    lines.push(line);
  };

  beforeEach(() => {
    folder = mkdtempSync(join(tmpdir(), 'notion-template-'));
    binding = join(folder, 'mapping.yaml');
    lines = [];
  });

  afterEach(() => {
    rmSync(folder, { recursive: true, force: true });
  });

  it('makes every canonical type and field an empty slot, and the App does not accept a binding with empty slots', () => {
    writeBindingTemplate({ canonical: CANONICAL, binding, log });

    const text = readFileSync(binding, 'utf8');
    const written = z
      .object({
        workspace: z.null(),
        data_sources: z.record(z.string(), z.null()),
        fields: z.record(z.string(), z.record(z.string(), z.null())),
      })
      .parse(parse(text));

    expect(Object.keys(written.data_sources)).toEqual(Object.keys(FIELD_CONTRACT));
    expect(
      Object.fromEntries(
        Object.entries(written.fields).map(([type, fields]) => [type, Object.keys(fields)]),
      ),
    ).toEqual(
      Object.fromEntries(
        Object.entries(FIELD_CONTRACT).map(([type, fields]) => [type, Object.keys(fields)]),
      ),
    );
    expect(text).toMatch(/Generated by `notion template` from contracts\/canonical\.yaml/);
    expect(() => loadBinding(text, binding)).toThrow();
    expect(lines).toEqual([`Skeleton written: ${binding}`]);
  });

  it('does not overwrite an existing binding', () => {
    writeFileSync(binding, 'workspace: workspace-1\n');

    expect(() => writeBindingTemplate({ canonical: CANONICAL, binding, log })).toThrow(
      /already exists/,
    );
    expect(readFileSync(binding, 'utf8')).toBe('workspace: workspace-1\n');
  });
});
